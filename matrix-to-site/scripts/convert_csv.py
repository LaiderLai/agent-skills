#!/usr/bin/env python3
"""Convert a feature-list CSV into feature-matrix YAML using a mapping file.

    python3 convert_csv.py --mapping mapping.yaml --csv features.csv --out <repo>/feature-matrix/data

Writes one YAML file per component plus _meta.yaml, then prints a verification
table comparing status counts in the CSV with the generated data. Exits 1 when
anything does not match or when the CSV contains status values the mapping
does not know, so a wrong mapping cannot slip through silently.

See references/mapping.md for the mapping format.
"""

import argparse
import collections
import csv
import io
import re
import string
import sys
from pathlib import Path

import yaml

# Spreadsheet exports are not always UTF-8 (Excel on Traditional Chinese Windows
# writes Big5/CP950, Western Windows CP1252). Try them in order and say which won.
ENCODINGS = ("utf-8-sig", "cp950", "cp1252")


def read_csv(path, encoding=None):
    """Return (rows, encoding) for a CSV file, trying common spreadsheet encodings."""
    data = Path(path).read_bytes()
    for enc in [encoding] if encoding else ENCODINGS:
        try:
            text = data.decode(enc)
        except UnicodeDecodeError:
            continue
        return list(csv.reader(io.StringIO(text, newline=""))), enc
    sys.exit(
        f"error: cannot decode {path} as {encoding or ', '.join(ENCODINGS)}; re-export as UTF-8 or pass --encoding"
    )


class IndentDumper(yaml.SafeDumper):
    """Indent block sequences under their key, as yamllint's default config expects."""

    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


META_HEADER = """\
# Feature matrix settings: platforms, status columns (platform x milestone),
# sections, and where the web editor commits. Generated by convert_csv.py;
# safe to edit by hand (e.g. add a milestone column or a platform).
"""


def clean(text):
    lines = [
        line.rstrip().expandtabs(4) for line in str(text or "").strip().splitlines()
    ]
    return re.sub(r"\n{3,}", "\n\n", "\n".join(lines)).strip()


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-") or "component"


def prune(value):
    """Drop empty strings / None from mappings so the YAML never contains '' (yamllint quote rules)."""
    if isinstance(value, dict):
        return {k: prune(v) for k, v in value.items() if v not in ("", None)}
    if isinstance(value, list):
        return [prune(v) for v in value]
    return value


class Converter:
    def __init__(self, mapping):
        self.m = mapping
        self.cols = mapping["columns"]
        self.values = {
            str(k).strip().upper(): v for k, v in mapping["status_values"].items()
        }
        self.markers = mapping.get("notes_markers") or {}
        self.head_platform = mapping.get("notes_head_platform")
        self.default_platform = mapping.get("notes_default_platform") or "general"
        if self.markers:
            names = "|".join(re.escape(k) for k in self.markers)
            self.marker_re = re.compile(rf"^[ \t]*\[({names})\][ \t]*", re.MULTILINE)
            self.inline_marker_re = re.compile(rf"\[({names})\]")
        self.sections = {}  # section value -> {id, name, description, notes}
        self.components = []
        self.unknown_values = collections.Counter()
        self.csv_counts = collections.defaultdict(collections.Counter)

    def cell(self, row, key):
        index = self.cols.get(key)
        if index is None or index >= len(row):
            return ""
        return row[index]

    def split_notes(self, text):
        """Split a notes cell into {platform|general: text} using line-leading [Marker]s."""
        text = clean(text)
        if not text:
            return {}
        if not self.markers:
            return {self.default_platform: text}
        found = list(self.marker_re.finditer(text))
        if not found:
            first_line = text.splitlines()[0]
            inline = self.inline_marker_re.search(first_line)
            if inline:
                return {self.markers[inline.group(1)]: text}
            return {self.default_platform: text}
        notes = {}
        head = clean(text[: found[0].start()])
        if head:
            notes[self.head_platform or "general"] = head
        for i, match in enumerate(found):
            end = found[i + 1].start() if i + 1 < len(found) else len(text)
            body = clean(text[match.end() : end])
            if body:
                key = self.markers[match.group(1)]
                notes[key] = "\n\n".join(filter(None, [notes.get(key), body]))
        return notes

    def section_for(self, value):
        if value not in self.sections:
            configured = (self.m.get("sections") or {}).get(value) or {}
            used = {s["id"] for s in self.sections.values()}
            free = next(c for c in string.ascii_uppercase if c not in used)
            self.sections[value] = {
                "id": configured.get("id", free),
                "name": configured.get("name", value),
                "description": configured.get("description", ""),
                "notes": {},
            }
        return self.sections[value]

    def new_component(self, section, name, raw_id, description, notes):
        number = None
        if raw_id:
            parts = re.findall(r"\d+", raw_id)
            if parts:
                number = int(parts[0])
        siblings = [c for c in self.components if c["_section"] is section]
        if number is None or any(c["_number"] == number for c in siblings):
            number = max([c["_number"] for c in siblings], default=0) + 1
        component = {
            "_section": section,
            "_number": number,
            "id": f"{section['id']}.{number}",
            "name": name,
            "description": description,
            "notes": notes,
            "features": [],
        }
        self.components.append(component)
        return component

    def run(self, csv_path):
        rows, self.encoding = read_csv(csv_path, self.m.get("encoding"))
        if self.encoding != "utf-8-sig":
            print(
                f"note: {csv_path} is not UTF-8; decoded as {self.encoding} (check names below look right)"
            )
        rows = rows[self.m.get("header_rows", 1) :]
        section = None
        component = None
        for row in rows:
            if not any(c.strip() for c in row):
                continue
            section_value = clean(self.cell(row, "section"))
            if section_value:
                section = self.section_for(section_value)
            if section is None:
                section = self.section_for("Features")
            raw_id = clean(self.cell(row, "component_id"))
            comp_name = clean(self.cell(row, "component"))
            name = clean(self.cell(row, "feature")) or clean(self.cell(row, "label"))
            comment = clean(self.cell(row, "comment"))
            notes = self.split_notes(self.cell(row, "notes"))

            if raw_id:  # component header row
                component = self.new_component(
                    section, comp_name or raw_id, raw_id, comment, notes
                )
                continue
            if not name:  # section header row: keep its description / notes
                if comment and not section["description"]:
                    section["description"] = comment
                for key, text in notes.items():
                    section["notes"].setdefault(key, text)
                continue
            starts_new = component is None or component["_section"] is not section
            if (
                "component_id" not in self.cols
                and comp_name
                and component
                and comp_name != component["name"]
            ):
                starts_new = True
            if starts_new:
                component = self.new_component(
                    section, comp_name or "General", "", "", {}
                )

            feature = {
                "id": f"{component['id']}.{len(component['features']) + 1}",
                "name": name,
            }
            label = clean(self.cell(row, "label"))
            if label and label != name:
                feature["label"] = label
            if comment:
                feature["comment"] = comment
            status = {}
            for col in self.m["status_columns"]:
                raw = (row[col["column"]] if col["column"] < len(row) else "").strip()
                if not raw:
                    continue
                value = self.values.get(raw.upper())
                if value is None:
                    self.unknown_values[(col["id"], raw)] += 1
                    continue
                status[col["id"]] = value
                self.csv_counts[col["id"]][value] += 1
            if status:
                feature["status"] = status
            if notes:
                feature["notes"] = notes
            component["features"].append(feature)

    def meta(self):
        m = self.m
        meta = {"title": m["title"]}
        for key in ("jira_url", "jira_projects"):
            if m.get(key):
                meta[key] = m[key]
        repo = m.get("repository") or {}
        meta["repository"] = {
            "name": repo.get("name", ""),
            "branch": repo.get("branch", "main"),
            "path": "feature-matrix/data",
            "tag_prefix": repo.get("tag_prefix", "matrix-table/"),
        }
        meta["platforms"] = m.get("platforms") or []
        meta["columns"] = [
            {k: v for k, v in col.items() if k != "column"}
            for col in m["status_columns"]
        ]
        meta["sections"] = []
        for s in self.sections.values():
            if not any(c["_section"] is s for c in self.components):
                continue
            entry = {"id": s["id"], "name": s["name"]}
            if s["description"]:
                entry["description"] = s["description"]
            if s["notes"]:
                entry["notes"] = s["notes"]
            meta["sections"].append(entry)
        return prune(meta)

    def write(self, out_dir):
        out_dir.mkdir(parents=True, exist_ok=True)
        for old in out_dir.glob("*.yaml"):
            old.unlink()

        def dump(data):
            return yaml.dump(
                data,
                Dumper=IndentDumper,
                sort_keys=False,
                allow_unicode=True,
                width=1000,
            )

        (out_dir / "_meta.yaml").write_text(
            META_HEADER + dump(self.meta()), encoding="utf-8"
        )
        for c in self.components:
            doc = {
                k: v
                for k, v in c.items()
                if not k.startswith("_") and v not in ("", {}, None)
            }
            doc.setdefault("features", [])
            name = f"{c['_section']['id']}.{c['_number']:02d}-{slug(c['name'])}.yaml"
            (out_dir / name).write_text(dump(doc), encoding="utf-8")

    def verify(self):
        """Compare status counts read from the CSV with counts in the generated features."""
        out_counts = collections.defaultdict(collections.Counter)
        features = 0
        for c in self.components:
            for f in c["features"]:
                features += 1
                for col, value in (f.get("status") or {}).items():
                    out_counts[col][value] += 1
        ok = True
        print(
            f"\n{len(self.components)} components, {features} features, {len(self.meta()['sections'])} sections"
        )
        print(f"{'column':24} {'csv':>28} {'yaml':>28}")
        for col in self.m["status_columns"]:
            a, b = dict(self.csv_counts[col["id"]]), dict(out_counts[col["id"]])
            mark = "OK" if a == b else "MISMATCH"
            ok &= a == b
            print(f"{col['id']:24} {a!s:>28} {b!s:>28}  {mark}")
        if not features:
            ok = False
            print(
                "error: no features found - wrong header_rows / columns, or an empty CSV"
            )
        empty = [c["id"] for c in self.components if not c["features"]]
        if empty:
            print(f"note: components without features: {', '.join(empty)}")
        if self.unknown_values:
            ok = False
            print(
                "\nerror: status values not in mapping.status_values (add them or fix the column):"
            )
            for (col, raw), n in self.unknown_values.most_common():
                print(f"  {col}: {raw!r} x{n}")
        notes = collections.Counter(
            k
            for c in self.components
            for f in c["features"]
            for k in (f.get("notes") or {})
        )
        print(f"notes by key: {dict(notes)}")
        return ok


def main():
    parser = argparse.ArgumentParser(
        description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter
    )
    parser.add_argument("--mapping", type=Path, required=True)
    parser.add_argument("--csv", type=Path, required=True)
    parser.add_argument(
        "--out",
        type=Path,
        required=True,
        help="output data directory, e.g. <repo>/feature-matrix/data",
    )
    parser.add_argument(
        "--dry-run", action="store_true", help="only print the verification table"
    )
    args = parser.parse_args()
    mapping = yaml.safe_load(args.mapping.read_text(encoding="utf-8"))
    converter = Converter(mapping)
    converter.run(args.csv)
    if not args.dry_run:
        converter.write(args.out)
        print(
            f"wrote {len(converter.components)} component files + _meta.yaml to {args.out}"
        )
    sys.exit(0 if converter.verify() else 1)


if __name__ == "__main__":
    main()
